namespace Ama.CRDT.Services.Journaling;

using System;
using System.Collections.Generic;
using System.Threading;
using System.Threading.Tasks;
using Ama.CRDT.Models;

/// <summary>
/// Defines a contract for an operation journal that captures explicitly generated 
/// and successfully applied CRDT operations, and provides access to retrieve them.
/// Implementing this interface allows external protocols to intercept operations 
/// in order to store them in an external datastore (e.g., event store, database, message queue) 
/// and serve them to other replicas.
/// </summary>
public interface ICrdtOperationJournal
{
    /// <summary>
    /// Synchronously appends a list of CRDT operations to the journal for a specific document.
    /// This is typically called when operations are generated via synchronous intent builders.
    /// </summary>
    /// <param name="documentId">The logical key or ID of the document.</param>
    /// <param name="operations">The list of operations to append.</param>
    void Append(IComparable documentId, IReadOnlyList<CrdtOperation> operations);

    /// <summary>
    /// Asynchronously appends a list of CRDT operations to the journal for a specific document.
    /// This is typically called when patches are applied or generated asynchronously.
    /// </summary>
    /// <param name="documentId">The logical key or ID of the document.</param>
    /// <param name="operations">The list of operations to append.</param>
    /// <param name="cancellationToken">A cancellation token that can be used to cancel the work.</param>
    /// <returns>A task that represents the asynchronous append operation.</returns>
    Task AppendAsync(IComparable documentId, IReadOnlyList<CrdtOperation> operations, CancellationToken cancellationToken = default);

    /// <summary>
    /// Retrieves operations generated by a specific origin replica within a contiguous range of shard clock values.
    /// </summary>
    /// <param name="shardId">The identifier of the shard to filter by.</param>
    /// <param name="originReplicaId">The identifier of the origin replica.</param>
    /// <param name="minShardClock">The exclusive minimum shard clock value (operations must have ShardClock > minShardClock).</param>
    /// <param name="maxShardClock">The inclusive maximum shard clock value (operations must have ShardClock &lt;= maxShardClock).</param>
    /// <param name="cancellationToken">A cancellation token.</param>
    /// <returns>An asynchronous stream of wrapped operations including their Document ID.</returns>
    IAsyncEnumerable<JournaledOperation> GetOperationsByRangeAsync(string shardId, string originReplicaId, long minShardClock, long maxShardClock, CancellationToken cancellationToken = default);

    /// <summary>
    /// Retrieves specific out-of-order operations (dots) generated by a specific origin replica for a shard.
    /// </summary>
    /// <param name="shardId">The identifier of the shard to filter by.</param>
    /// <param name="originReplicaId">The identifier of the origin replica.</param>
    /// <param name="shardClocks">A set of specific shard clock values to retrieve.</param>
    /// <param name="cancellationToken">A cancellation token.</param>
    /// <returns>An asynchronous stream of wrapped operations including their Document ID.</returns>
    IAsyncEnumerable<JournaledOperation> GetOperationsByDotsAsync(string shardId, string originReplicaId, IEnumerable<long> shardClocks, CancellationToken cancellationToken = default);
}